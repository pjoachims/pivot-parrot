/**
 * Generate a friendly name from a formula/expression
 * Handles common SQL aggregations and cleans up field names
 */

/**
 * Convert snake_case, camelCase, or PascalCase to Title Case
 */
function toTitleCase(str: string): string {
  // Handle snake_case
  str = str.replace(/_/g, ' ');

  // Handle camelCase/PascalCase by inserting spaces before capitals
  str = str.replace(/([a-z])([A-Z])/g, '$1 $2');

  // Capitalize first letter of each word
  return str
    .split(' ')
    .map(word => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
    .join(' ');
}

/**
 * Extract the main field/metric name from a formula
 */
function extractMainIdentifier(formula: string): string | null {
  // Remove whitespace
  const cleaned = formula.trim();

  // Pattern 1: Aggregation functions like SUM(field), COUNT(field), AVG(field), etc.
  const aggMatch = cleaned.match(/^(SUM|AVG|COUNT|MIN|MAX|COUNT_IF|SUM_IF|AVG_IF)\s*\(\s*([^)]+?)\s*(?:::|[)])/i);
  if (aggMatch) {
    const funcName = aggMatch[1].toUpperCase();
    let fieldName = aggMatch[2].trim();

    // Remove type casts like ":: boolean"
    fieldName = fieldName.replace(/\s*::\s*\w+\s*$/, '');

    // Map function names to friendly versions
    const funcMap: Record<string, string> = {
      'SUM': 'Sum',
      'AVG': 'Average',
      'COUNT': 'Count',
      'MIN': 'Min',
      'MAX': 'Max',
      'COUNT_IF': 'Count',
      'SUM_IF': 'Sum',
      'AVG_IF': 'Average'
    };

    return `${funcMap[funcName]} ${toTitleCase(fieldName)}`;
  }

  // Pattern 2: Metric references like {{ Metric Name }}
  const metricRefMatch = cleaned.match(/^\{\{\s*([^}]+?)\s*\}\}/);
  if (metricRefMatch) {
    return metricRefMatch[1].trim();
  }

  // Pattern 3: Simple field name or expression
  // Try to extract the first identifier
  const identifierMatch = cleaned.match(/^([a-zA-Z_][a-zA-Z0-9_]*)/);
  if (identifierMatch) {
    return toTitleCase(identifierMatch[1]);
  }

  return null;
}

/**
 * Generate a friendly name from a formula
 * Falls back to a simple pattern if parsing fails
 */
export function generateFriendlyName(formula: string, type: 'metric' | 'filter' | 'grouping' = 'metric'): string {
  if (!formula || !formula.trim()) {
    const typeMap = {
      'metric': 'Metric',
      'filter': 'Filter',
      'grouping': 'Grouping'
    };
    return `New ${typeMap[type]}`;
  }

  const identifier = extractMainIdentifier(formula);

  if (identifier) {
    return identifier;
  }

  // Fallback: Clean up the formula itself
  let cleaned = formula.trim();

  // Truncate if too long
  if (cleaned.length > 30) {
    cleaned = cleaned.substring(0, 27) + '...';
  }

  // Replace operators with friendlier symbols
  cleaned = cleaned
    .replace(/\*/g, '×')
    .replace(/\//g, '÷')
    .replace(/>=?/g, '≥')
    .replace(/<=?/g, '≤')
    .replace(/!=/g, '≠');

  return cleaned;
}

/**
 * Check if a name appears to be auto-generated (helps decide whether to update it)
 */
export function isAutoGeneratedName(name: string): boolean {
  if (!name) return true;

  // Empty or just whitespace
  if (!name.trim()) return true;

  // Matches pattern "New Metric", "New Filter", etc.
  if (/^New (Metric|Filter|Grouping)$/i.test(name)) return true;

  // Matches pattern "custom_..." (old auto-generated pattern)
  if (/^custom_\d+$/i.test(name)) return true;

  return false;
}

/**
 * Convert a name to a friendly ID (slug format)
 * E.g., "Sum of Sales" -> "sum_of_sales"
 */
export function nameToId(name: string): string {
  return name
    .trim()
    .toLowerCase()
    // Replace spaces and special characters with underscores
    .replace(/[^a-z0-9]+/g, '_')
    // Remove leading/trailing underscores
    .replace(/^_+|_+$/g, '')
    // Collapse multiple underscores
    .replace(/_+/g, '_')
    // Limit length to 50 characters
    .substring(0, 50)
    // Remove trailing underscore if truncation created one
    .replace(/_+$/, '');
}

/**
 * Generate a unique ID from a name, checking against existing IDs
 * Adds numbers (1, 2, 3...) if the ID already exists
 */
export function generateUniqueId(name: string, existingIds: string[], prefix: string = 'custom'): string {
  const baseId = nameToId(name) || 'metric'; // fallback if name is empty/invalid
  let candidateId = `${prefix}_${baseId}`;

  // If no collision, use as-is
  if (!existingIds.includes(candidateId)) {
    return candidateId;
  }

  // Otherwise, add a number
  let counter = 1;
  while (existingIds.includes(`${candidateId}_${counter}`)) {
    counter++;
  }

  return `${candidateId}_${counter}`;
}
