import React, { useState, useEffect, useRef, useMemo } from 'react';
import BaseDialog from '../../shared/BaseDialog';
import { validateCustomMetric } from './custom-expression/validation';
import { HelpButtons, HelpContent } from './custom-expression/HelpContent';
import { FormatSection } from './custom-expression/FormatSection';
import { CaseBuilder, buildCaseSQL } from './custom-expression/CaseBuilder';
import { generateFriendlyName, isAutoGeneratedName } from '../../../application/utils/nameGenerator';
import { clearResolverCache, buildReferenceLookup } from '../../../domain/field/derived-field-resolver-v2';
import type { PivotTableConfig } from '../../../domain/models/types';

const TYPE_CONFIG = {
  metric: {
    title: 'Custom Metric',
    placeholder: 'e.g., SUM(sales) / SUM(quantity)',
    buttonText: 'Create Metric',
    showFormat: true
  },
  filter: {
    title: 'Custom Filter',
    placeholder: 'e.g., sales > 1000 AND region != \'Asia\'',
    buttonText: 'Create Filter',
    showFormat: false
  },
  grouping: {
    title: 'Custom Grouping',
    placeholder: 'e.g., YEAR(date) or LEFT(name, 1)',
    buttonText: 'Create Grouping',
    showFormat: false
  }
};

export default function CustomExpressionDialog({
  type = 'metric', // 'metric' | 'filter' | 'grouping'
  onSave,
  onCancel,
  initialName = '',
  initialFormula = '',
  initialFormat = null,
  availableMetrics = [],
  availableFields = [],
  config = {} as Partial<PivotTableConfig>,
  editingId = null
}) {
  const typeConfig = TYPE_CONFIG[type];
  const fieldId = React.useId();

  const [name, setName] = useState(initialName);
  const [formula, setFormula] = useState(initialFormula);
  const [error, setError] = useState('');
  const [showHelp, setShowHelp] = useState(null); // 'explanation' | 'examples' | 'metrics'

  // Case builder state (for groupings)
  const [useCaseBuilder, setUseCaseBuilder] = useState(false);
  const [caseConditions, setCaseConditions] = useState([{ when: '', then: '' }]);
  const [elseResult, setElseResult] = useState('');

  // Sync case builder to formula
  const handleCaseBuilderChange = (conditions: typeof caseConditions, elseVal: string) => {
    setCaseConditions(conditions);
    setElseResult(elseVal);
    const sql = buildCaseSQL(conditions, elseVal);
    setFormula(sql);
    setError('');
  };

  // Build reference lookup for {{}} validation (exclude field being edited to prevent self-reference)
  const referenceLookup = useMemo(() => {
    const customMetrics = (config.customMetrics || []).filter(m => m.id !== editingId);
    const customFilters = (config.customFilters || []).filter(f => f.id !== editingId);
    const customGroupings = (config.customGroupings || []).filter(g => g.id !== editingId);

    return buildReferenceLookup({
      availableFields,
      customGroupings,
      customFilters,
      customMetrics,
      includeMetrics: true  // Include all types for validation
    });
  }, [availableFields, config.customMetrics, config.customFilters, config.customGroupings, editingId]);

  // Track whether the user has manually edited the name
  const [nameManuallyEdited, setNameManuallyEdited] = useState(!isAutoGeneratedName(initialName));
  const isInitialMount = useRef(true);

  // Format options (only for metrics)
  const [formatType, setFormatType] = useState(initialFormat?.type || 'auto');
  const [decimals, setDecimals] = useState(initialFormat?.decimals ?? 2);
  const [currency, setCurrency] = useState(initialFormat?.currency || 'USD');
  const [useThousandSeparator, setUseThousandSeparator] = useState(
    initialFormat?.useThousandSeparator ?? (initialFormat?.type === 'currency')
  );

  // Auto-generate name from formula when formula changes
  // But only if the name hasn't been manually edited by the user
  useEffect(() => {
    // Skip on initial mount if we already have a name
    if (isInitialMount.current) {
      isInitialMount.current = false;
      if (initialName) {
        return;
      }
    }

    // Only auto-generate if the name hasn't been manually edited
    if (!nameManuallyEdited && formula.trim()) {
      const generatedName = generateFriendlyName(formula, type as 'metric' | 'filter' | 'grouping');
      setName(generatedName);
    }
  }, [formula, type, nameManuallyEdited, initialName]);

  const handleSave = () => {
    // Validate
    const validationError = validateCustomMetric(name, formula, availableMetrics, {
      referenceLookup
    });
    if (validationError) {
      setError(validationError.error);
      return;
    }

    const saveData: Record<string, unknown> = {
      name: name.trim(),
      formula: formula.trim()
    };

    // Add format only for metrics and only if user explicitly set it (not auto)
    if (typeConfig.showFormat && formatType !== 'auto') {
      saveData.format = {
        type: formatType,
        decimals: parseInt(decimals),
        currency,
        useThousandSeparator
      };
    }

    // Clear resolver cache before saving (field definitions are changing)
    clearResolverCache();

    onSave(saveData);
    onCancel(); // Auto-close on successful save
  };

  return (
    <BaseDialog
      title={initialName ? `Edit ${typeConfig.title}` : `Create ${typeConfig.title}`}
      onClose={onCancel}
      onSubmit={handleSave}
      submitLabel={initialName ? 'Save' : typeConfig.buttonText}
      showCancelButton
    >
          <div className="pp-field">
            <label className="pp-label" htmlFor={`${fieldId}-name`}>Name</label>
            <input
              id={`${fieldId}-name`}
              type="text"
              value={name}
              onChange={(e) => {
                setName(e.target.value);
                setNameManuallyEdited(true); // Mark as manually edited
                setError('');
              }}
              placeholder={`e.g., My ${typeConfig.title}`}
              className="pp-input"
              autoFocus
            />
          </div>

          <div className="pp-field">
            <div className="pp-label-row">
              <label className="pp-label" htmlFor={`${fieldId}-formula`}>
                {type === 'filter' ? 'SQL Expression' : 'Formula'}
              </label>
              {type === 'grouping' && (
                <label className="pp-check">
                  <input
                    type="checkbox"
                    checked={useCaseBuilder}
                    onChange={(e) => setUseCaseBuilder(e.target.checked)}
                  />
                  Case Builder
                </label>
              )}
            </div>

            {type === 'grouping' && useCaseBuilder ? (
              <CaseBuilder
                conditions={caseConditions}
                elseResult={elseResult}
                onChange={handleCaseBuilderChange}
              />
            ) : (
              <textarea
                id={`${fieldId}-formula`}
                value={formula}
                onChange={(e) => {
                  setFormula(e.target.value);
                  setError('');
                }}
                placeholder={typeConfig.placeholder}
                className="pp-textarea"
                rows={4}
                spellCheck={false}
              />
            )}

            {type === 'metric' && (
              <>
                <HelpButtons
                  showHelp={showHelp}
                  setShowHelp={setShowHelp}
                  availableMetrics={availableMetrics}
                />
                <HelpContent
                  showHelp={showHelp}
                  availableMetrics={availableMetrics}
                  formula={formula}
                  setFormula={setFormula}
                  setShowHelp={setShowHelp}
                />
              </>
            )}
          </div>

          {typeConfig.showFormat && (
            <FormatSection
              formatType={formatType}
              setFormatType={setFormatType}
              decimals={decimals}
              setDecimals={setDecimals}
              currency={currency}
              setCurrency={setCurrency}
              useThousandSeparator={useThousandSeparator}
              setUseThousandSeparator={setUseThousandSeparator}
            />
          )}

          {error && (
            <div className="pp-alert" role="alert">{error}</div>
          )}
    </BaseDialog>
  );
}
